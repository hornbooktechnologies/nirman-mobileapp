/* Run from any directory: node scripts/inventory-form-validation.cjs */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'apps/web/node_modules/typescript'));
const files = (directory) => fs.existsSync(directory) ? fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? files(path.join(directory, entry.name)) : [path.join(directory, entry.name)]) : [];
const clean = (value) => value.replace(/\s+/g, ' ').replace(/\|/g, '\\|').slice(0, 180);
const rows = [];
for (const platform of ['web', 'mobile']) {
  const directories = [path.join(root, `apps/${platform}/src/features`)];
  if (platform === 'web') directories.push(path.join(root, 'apps/web/src/app/(auth)'));
  for (const file of directories.flatMap(files).filter((file) => file.endsWith('.tsx'))) {
    const source = fs.readFileSync(file, 'utf8');
    const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    const relative = path.relative(root, file).replaceAll('\\', '/');
    const module = relative.split('/features/')[1]?.split('/')[0] ?? 'auth';
    const controls = [];
    function visit(node) {
      if (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) {
        const tag = node.tagName.getText(sf);
        if (['Input', 'PasswordInput', 'DateInput', 'TimeInput', 'Select', 'Textarea', 'SearchableSelect', 'input', 'select', 'textarea'].includes(tag)) {
          const attrs = Object.fromEntries(node.attributes.properties.filter(ts.isJsxAttribute).map((attr) => [attr.name.getText(sf), attr.initializer?.getText(sf) ?? 'true']));
          let parent = node.parent;
          let field;
          while (parent && !ts.isFunctionLike(parent)) {
            if (ts.isJsxElement(parent) && ['FormField', 'ValidatedField', 'label'].includes(parent.openingElement.tagName.getText(sf))) { field = parent; break; }
            parent = parent.parent;
          }
          const fieldAttrs = field ? Object.fromEntries(field.openingElement.attributes.properties.filter(ts.isJsxAttribute).map((attr) => [attr.name.getText(sf), attr.initializer?.getText(sf) ?? 'true'])) : {};
          const label = (fieldAttrs.label ?? attrs.name ?? attrs.id ?? attrs.accessibilityLabel ?? attrs['aria-label'] ?? attrs.placeholder ?? clean(field?.children.filter(ts.isJsxText).map((child) => child.getText(sf)).join(' ') ?? '')) || '(dynamic/unlabelled)';
          const rules = ['required', 'min', 'max', 'minLength', 'maxLength', 'pattern', 'type', 'keyboardType'].filter((key) => attrs[key] || fieldAttrs[key]).map((key) => `${key}=${attrs[key] ?? fieldAttrs[key]}`).join('; ') || 'Module handler / optional';
          const line = sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
          controls.push({ label: clean(label), rules: clean(rules), line, value: clean(attrs.value ?? '(uncontrolled)'), error: clean(fieldAttrs.error ?? attrs.invalid ?? ''), validator: clean(fieldAttrs.validate ?? '') });
        }
      }
      ts.forEachChild(node, visit);
    }
    visit(sf);
    if (controls.length) rows.push({ platform, module, file: relative, controls });
  }
}
rows.sort((a, b) => a.module.localeCompare(b.module) || a.platform.localeCompare(b.platform) || a.file.localeCompare(b.file));
let markdown = '# Form validation inventory\n\nGenerated by `node scripts/inventory-form-validation.cjs`. Includes editing controls and filters so omissions remain visible. Dynamic schema-driven rows are expanded by their existing module validators at runtime. Public marketing website excluded.\n\n';
markdown += 'Verification: shared foundation browser/unit checks and Web/Mobile typechecks cover the adapter. Individual authenticated workflows and physical-device acceptance remain pending; presence here does not mark a module accepted. Module API DTOs/services and approved contracts remain authoritative; existing UI attributes are the recorded constraints, not a declaration that the API audit is complete.\n\n';
for (const module of [...new Set(rows.map((row) => row.module))]) {
  markdown += `## ${module}\n\n`;
  const apiModule = ({ 'user-management': 'users', 'team': 'projects', 'members': 'organizations', 'total-expenses': 'source-payments' })[module] ?? module;
  const api = files(path.join(root, 'apps/api/src/modules', apiModule)).filter((file) => /dto[\\/].*\.ts$/.test(file));
  markdown += `API source: \`apps/api/src/modules/${apiModule}/\` (${api.length} DTO files; check service-level and nested rules as well).\n\n`;
  for (const row of rows.filter((row) => row.module === module)) {
    markdown += `### ${row.platform}: \`${row.file}\`\n\n| Field / identifier | Existing constraints / required condition | Value / binding | Existing inline error / validator |\n| --- | --- | --- | --- |\n`;
    for (const control of row.controls) markdown += `| ${control.label} (L${control.line}) | ${control.rules} | ${control.value} | ${control.validator || control.error || 'Shared field adapter / module handler'} |\n`;
    markdown += '\n';
  }
}
fs.writeFileSync(path.join(root, 'docs/tasks/form-validation-inventory.md'), markdown);
console.log(`Inventoried ${rows.length} files and ${rows.reduce((sum, row) => sum + row.controls.length, 0)} controls.`);
